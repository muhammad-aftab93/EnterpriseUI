namespace EnterpriseUI.CodeGenerators;

/// <summary>
/// Source code emission and component metadata reflection generator.
/// </summary>
public static class ComponentCodeGenerator
{
    public static string GenerateRegistrationSource(IEnumerable<string> componentTypes)
    {
        var lines = componentTypes.Select(t => $"        services.AddTransient<{t}>();");
        return $@"// <auto-generated/>
using Microsoft.Extensions.DependencyInjection;

public static class EnterpriseUIServiceCollectionExtensions
{{
    public static IServiceCollection AddEnterpriseUI(this IServiceCollection services)
    {{
{string.Join("\n", lines)}
        return services;
    }}
}}";
    }
}

